# register-startup.ps1 -- make both services start with Windows and stop with the DSH client.
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\register-startup.ps1
# Adds one .cmd to the user's Startup folder (no admin rights, no scheduled task).
# ASCII ONLY.

$root = Split-Path $PSScriptRoot -Parent
$startup = [Environment]::GetFolderPath('Startup')
$target = Join-Path $startup 'DSH-Voice-Guard.cmd'
$guard = Join-Path $root 'asr\guard-asr.ps1'
$asrCmd = Join-Path $root 'asr\asr-server.cmd'
$ttsCmd = Join-Path $root 'tts\tts-server.cmd'

$body = @"
@echo off
rem Auto-generated by scripts\register-startup.ps1 -- starts the local voice services.
rem ASCII ONLY.
start "" /min powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "$guard" -Port 18080 -Server "$asrCmd" -LogName asr-server
start "" /min powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "$guard" -Port 18081 -Server "$ttsCmd" -LogName tts-server
exit /b 0
"@

[IO.File]::WriteAllText($target, $body, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("wrote " + $target)
Write-Host 'It runs at logon. Delete that file to undo.'
